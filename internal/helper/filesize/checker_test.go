func TestCheckerRetainedReasonsProduceVerifiableReports(t *testing.T) {
	type scenario struct {
		files  map[string][]byte
		policy Policy
		reason string
	}
	makeException := func(path, category string, data []byte) (Policy, Exception) {
		exception := validException(path, category)
		exception.ContentSHA256 = digestBytes(data)
		policy := validPolicy()
		policy.Exceptions = []Exception{exception}
		return policy, exception
	}

	script301 := lineData(301)
	approvedPolicy, _ := makeException("scripts/approved.sh", "script", script301)
	expiredPolicy, expired := makeException("scripts/expired.sh", "script", script301)
	expired.ExpiresOn = "2026-08-18"
	expiredPolicy.Exceptions[0] = expired
	staleData := lineData(300)
	stalePolicy, _ := makeException("scripts/stale.sh", "script", staleData)
	digestPolicy, digestException := makeException("scripts/digest.sh", "script", script301)
	digestException.ContentSHA256 = strings.Repeat("b", 64)
	digestPolicy.Exceptions[0] = digestException
	maxData := lineData(700)
	maxPolicy, maxException := makeException("scripts/max.sh", "script", maxData)
	maxException.ApprovedMaxPhysicalLines = 600
	maxPolicy.Exceptions[0] = maxException
	wrongClassData := headerData(801, "# ", "coh-test-generator")
	wrongClassPolicy, _ := makeException("docs/vendor-long.md", "vendor", wrongClassData)
	headerDataMissing := lineData(801)
	headerPolicy, _ := makeException("contracts/missing.schema.json", "schema", headerDataMissing)
	binaryData := []byte{0xff, 0x00}
	binaryPolicy, _ := makeException("assets/binary.bin", "generated", binaryData)
	missingPolicy, _ := makeException("scripts/missing.sh", "script", script301)

	scenarios := map[string]scenario{
		"warning_threshold":                  {map[string][]byte{"docs/warning.md": lineData(501)}, validPolicy(), "warning_threshold"},
		"script_limit":                       {map[string][]byte{"scripts/denied.sh": script301}, validPolicy(), "script_limit"},
		"production_hard_limit":              {map[string][]byte{"internal/large.go": lineData(801)}, validPolicy(), "production_hard_limit"},
		"governed_asset_hard_limit":          {map[string][]byte{"contracts/large.schema.json": lineData(801)}, validPolicy(), "governed_asset_hard_limit"},
		"classified_binary_input":            {map[string][]byte{"assets/binary.bin": binaryData}, binaryPolicy, "classified_binary_input"},
		"approved_exception":                 {map[string][]byte{"scripts/approved.sh": script301}, approvedPolicy, "approved_exception"},
		"exception_expired":                  {map[string][]byte{"scripts/expired.sh": script301}, expiredPolicy, "exception_expired"},
		"exception_stale_below_limit":        {map[string][]byte{"scripts/stale.sh": staleData}, stalePolicy, "exception_stale_below_limit"},
		"exception_content_digest_mismatch":  {map[string][]byte{"scripts/digest.sh": script301}, digestPolicy, "exception_content_digest_mismatch"},
		"exception_approved_max_exceeded":    {map[string][]byte{"scripts/max.sh": maxData}, maxPolicy, "exception_approved_max_exceeded"},
		"exception_class_mismatch":           {map[string][]byte{"docs/vendor-long.md": wrongClassData}, wrongClassPolicy, "exception_class_mismatch"},
		"exception_generated_header_missing": {map[string][]byte{"contracts/missing.schema.json": headerDataMissing}, headerPolicy, "exception_generated_header_missing"},
		"exception_target_missing":           {map[string][]byte{"docs/safe.md": []byte("safe\n")}, missingPolicy, "exception_target_missing"},
	}
	for name, test := range scenarios {
		t.Run(name, func(t *testing.T) {
			report, err := runMemoryCheck(t, test.files, test.policy, "2026-08-19")
			if test.reason == "warning_threshold" || test.reason == "approved_exception" {
				requirePassed(t, report, err)
			} else {
				requireCode(t, err, CodeDenied)
			}
			if len(report.Findings) != 1 || report.Findings[0].Reason != test.reason {
				t.Fatalf("findings=%+v", report.Findings)
			}
			path := filepath.Join(t.TempDir(), "report.json")
			if err := WriteReportAtomic(path, &report); err != nil {
				t.Fatalf("WriteReportAtomic() error = %v", err)
			}
			if _, err := ReadAndVerifyReport(path); err != nil {
				t.Fatalf("ReadAndVerifyReport() error = %v", err)
			}
		})
	}
}
