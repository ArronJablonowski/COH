func TestCheckerScriptClassificationPrecedence(t *testing.T) {
	cases := map[string]memoryFile{
		"scripts/name.txt":             {data: lineData(301), mode: 0o644},
		".github/workflows/gate.yml":   {data: lineData(301), mode: 0o644},
		"db/migrations/001.data":       {data: lineData(301), mode: 0o644},
		"build/Dockerfile.generated":   {data: lineData(301), mode: 0o644},
		"build/Makefile":               {data: lineData(301), mode: 0o644},
		"build/Taskfile.generated.yml": {data: lineData(301), mode: 0o644},
		"bin/tool":                     {data: append([]byte("#!/bin/bash\n"), lineData(300)...), mode: 0o755},
	}
	for path, file := range cases {
		t.Run(path, func(t *testing.T) {
			source := &memorySource{files: map[string]memoryFile{path: file}}
			checker := NewChecker(source)
			checker.now = func() time.Time { return time.Date(2026, 8, 19, 0, 0, 0, 0, time.UTC) }
			report, err := checker.Check(context.Background(), Request{Root: "ignored", Policy: validPolicy()})
			requireCode(t, err, CodeDenied)
			if report.Findings[0].Class != "script" {
				t.Fatalf("class=%q", report.Findings[0].Class)
			}
		})
	}
}

func TestCheckerExceptionLifecycle(t *testing.T) {
	data := lineData(301)
	base := validException("scripts/legacy.sh", "script")
	base.ContentSHA256 = digestBytes(data)
	base.ApprovedMaxPhysicalLines = 800
	for name, configure := range map[string]func(*Exception, *string){
		"inclusive_expiry": func(_ *Exception, date *string) { *date = "2026-08-19" },
		"future_expiry":    func(value *Exception, date *string) { value.ExpiresOn = "2026-08-20"; *date = "2026-08-19" },
	} {
		t.Run(name, func(t *testing.T) {
			exception := base
			date := "2026-08-19"
			configure(&exception, &date)
			policy := validPolicy()
			policy.Exceptions = []Exception{exception}
			report, err := runMemoryCheck(t, map[string][]byte{exception.Path: data}, policy, date)
			requirePassed(t, report, err)
			if report.Counts.Exceptions != 1 || report.Findings[0].Reason != "approved_exception" {
				t.Fatalf("exception report=%+v", report)
			}
		})
	}
	for name, mutate := range map[string]func(*Exception, *map[string][]byte, *string){
		"expired": func(value *Exception, _ *map[string][]byte, date *string) { *date = "2026-08-20" },
		"stale": func(value *Exception, files *map[string][]byte, _ *string) {
			(*files)[value.Path] = lineData(300)
			value.ContentSHA256 = digestBytes((*files)[value.Path])
		},
		"digest": func(value *Exception, _ *map[string][]byte, _ *string) { value.ContentSHA256 = strings.Repeat("b", 64) },
		"approved_max": func(value *Exception, files *map[string][]byte, _ *string) {
			(*files)[value.Path] = lineData(700)
			value.ContentSHA256 = digestBytes((*files)[value.Path])
			value.ApprovedMaxPhysicalLines = 600
		},
		"missing": func(value *Exception, files *map[string][]byte, _ *string) {
			*files = map[string][]byte{"docs/safe.md": []byte("safe\n")}
		},
	} {
		t.Run(name, func(t *testing.T) {
			exception := base
			files := map[string][]byte{exception.Path: data}
			date := "2026-08-19"
			mutate(&exception, &files, &date)
			policy := validPolicy()
			policy.Exceptions = []Exception{exception}
			_, err := runMemoryCheck(t, files, policy, date)
			requireCode(t, err, CodeDenied)
		})
	}
}

