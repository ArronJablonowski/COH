func TestCheckerPhysicalLineBoundaries(t *testing.T) {
	cases := []struct {
		name, path string
		lines      int
		warnings   int
		denied     bool
	}{
		{"production_499", "internal/example.go", 499, 0, false},
		{"production_500", "internal/example.go", 500, 0, false},
		{"production_501", "internal/example.go", 501, 1, false},
		{"production_800", "internal/example.go", 800, 1, false},
		{"production_801", "internal/example.go", 801, 0, true},
		{"other_500", "docs/example.md", 500, 0, false},
		{"other_501", "docs/example.md", 501, 1, false},
		{"other_800", "docs/example.md", 800, 1, false},
		{"other_801", "docs/example.md", 801, 1, false},
		{"script_299", "scripts/example.sh", 299, 0, false},
		{"script_300", "scripts/example.sh", 300, 0, false},
		{"script_301", "scripts/example.sh", 301, 0, true},
	}
	for _, test := range cases {
		t.Run(test.name, func(t *testing.T) {
			report, err := runMemoryCheck(t, map[string][]byte{test.path: lineData(test.lines)}, validPolicy(), "2026-08-19")
			if test.denied {
				requireCode(t, err, CodeDenied)
				if report.Counts.Denials != 1 || report.Outcome != "denied" {
					t.Fatalf("denial report = %+v", report)
				}
				return
			}
			requirePassed(t, report, err)
			if report.Counts.Warnings != test.warnings {
				t.Fatalf("warnings=%d, want %d", report.Counts.Warnings, test.warnings)
			}
		})
	}
}

func TestPhysicalLineEncodingCases(t *testing.T) {
	for name, data := range map[string][]byte{
		"empty": nil, "no_final_newline": []byte("one"), "crlf": []byte("one\r\ntwo\r\n"),
		"huge_line": []byte(strings.Repeat("x", 1<<20)),
	} {
		t.Run(name, func(t *testing.T) {
			report, err := runMemoryCheck(t, map[string][]byte{"docs/input.txt": data}, validPolicy(), "2026-08-19")
			requirePassed(t, report, err)
		})
	}
	if physicalLines([]byte("one")) != 1 || physicalLines([]byte("one\r\ntwo\r\n")) != 2 || physicalLines(nil) != 0 {
		t.Fatal("physical line counter does not implement the locked EOF/CRLF contract")
	}
}

func TestPhysicalLineThresholdsAcrossEOFAndCRLF(t *testing.T) {
	type boundary struct {
		path     string
		lines    int
		warnings int
		denied   bool
	}
	boundaries := []boundary{
		{"scripts/input.sh", 299, 0, false}, {"scripts/input.sh", 300, 0, false}, {"scripts/input.sh", 301, 0, true},
		{"docs/input.md", 499, 0, false}, {"docs/input.md", 500, 0, false}, {"docs/input.md", 501, 1, false},
		{"docs/input.md", 800, 1, false}, {"docs/input.md", 801, 1, false},
	}
	encodings := map[string]func(int) []byte{
		"lf_final": lineData,
		"no_final_lf": func(lines int) []byte {
			if lines == 0 {
				return nil
			}
			return []byte(strings.Repeat("x\n", lines-1) + "x")
		},
		"crlf": func(lines int) []byte { return []byte(strings.Repeat("x\r\n", lines)) },
	}
	for encoding, encode := range encodings {
		for _, test := range boundaries {
			name := encoding + "_" + strings.ReplaceAll(test.path, "/", "_") + "_" + decimal(test.lines)
			t.Run(name, func(t *testing.T) {
				report, err := runMemoryCheck(t, map[string][]byte{test.path: encode(test.lines)}, validPolicy(), "2026-08-19")
				if test.denied {
					requireCode(t, err, CodeDenied)
				} else {
					requirePassed(t, report, err)
				}
				if report.Counts.Warnings != test.warnings || physicalLines(encode(test.lines)) != test.lines {
					t.Fatalf("report=%+v physicalLines=%d", report.Counts, physicalLines(encode(test.lines)))
				}
			})
		}
	}
}

func TestGeneratedHeaderFormsAndFirstFiveLineBoundary(t *testing.T) {
	for position := 1; position <= 6; position++ {
		data := []byte(strings.Repeat("ordinary\n", position-1) + "// Code generated by tool; DO NOT EDIT.\n")
		if got := generatedHeader(data, "tool"); got != (position <= 5) {
			t.Fatalf("position %d accepted=%t", position, got)
		}
	}
	for name, line := range map[string]string{
		"slash":        "// Code generated by tool; DO NOT EDIT.",
		"hash":         "# Code generated by tool; DO NOT EDIT.",
		"sql":          "-- Code generated by tool; DO NOT EDIT.",
		"block":        "/* Code generated by tool; DO NOT EDIT. */",
		"block_middle": "* Code generated by tool; DO NOT EDIT.",
		"json":         `"$comment": "Code generated by tool; DO NOT EDIT.",`,
	} {
		t.Run(name, func(t *testing.T) {
			if !generatedHeader([]byte(line+"\n"), "tool") {
				t.Fatalf("supported header form rejected: %q", line)
			}
		})
	}
	for name, data := range map[string][]byte{
		"mismatch": []byte("// Code generated by other; DO NOT EDIT.\n"),
		"missing":  []byte("// ordinary comment\n"),
		"late":     []byte("1\n2\n3\n4\n5\n// Code generated by tool; DO NOT EDIT.\n"),
	} {
		if generatedHeader(data, "tool") {
			t.Fatalf("%s invalid header accepted", name)
		}
	}
}

